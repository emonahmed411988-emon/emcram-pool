export function getStrikerDef(id: string): StrikerDef {
  return STRIKERS.find((s) => s.id === id) || STRIKERS[0];
}

export function getStrikerStats(
  id: string,
  level: number,
  collectionLevel: number
): { force: number; aim: number; time: number } {
  const def = getStrikerDef(id);
  const lvlBonus = Math.max(0, level - 1);
  let force = Math.min(def.maxForce, def.baseForce + lvlBonus);
  let aim = Math.min(def.maxAim, def.baseAim + lvlBonus);
  let time = Math.min(def.maxTime, def.baseTime + Math.floor(lvlBonus * 0.8));

  for (const p of POWERS) {
    if (collectionLevel >= p.unlockLevel) {
      if (p.bonusForce) force = Math.min(10, force + p.bonusForce);
      if (p.bonusAim) aim = Math.min(10, aim + p.bonusAim);
      if (p.bonusTime) time = Math.min(10, time + p.bonusTime);
    }
  }
  return { force, aim, time };
}
